/**
 * Writes public/_redirects (Cloudflare format) from src/registry/redirects.ts.
 * Runs at prebuild; the output file is git-ignored.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { redirects } from "../src/registry/redirects";

const lines = redirects.flatMap(({ from, to, status }) => [
  `${from} ${to} ${status}`,
  `${from.slice(0, -1)} ${to} ${status}`,
]);

const out = resolve(import.meta.dirname, "../public/_redirects");
writeFileSync(
  out,
  `# Generated by scripts/generate-redirects.ts. Do not edit.\n${lines.join("\n")}\n`,
);
console.log(`_redirects: ${lines.length} rules`);
