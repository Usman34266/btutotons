/**
 * Writes public/_headers (Cloudflare format). Runs at prebuild.
 *
 * CSP: static export cannot use nonces, so script-src allows 'unsafe-inline'
 * (Next.js inline bootstrap + next-themes script). Tighten with build-time
 * hashes later; see docs/DECISIONS.md.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ANALYTICS_SCRIPT = "https://static.cloudflareinsights.com";
const ANALYTICS_BEACON = "https://cloudflareinsights.com";

const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline' ${ANALYTICS_SCRIPT}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  `connect-src 'self' ${ANALYTICS_BEACON}`,
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

const rules: Record<string, Record<string, string>> = {
  "/*": {
    "Strict-Transport-Security": "max-age=31536000; includeSubDomains",
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
    "X-Frame-Options": "DENY",
    "Content-Security-Policy": csp,
  },
  "/_next/static/*": {
    "Cache-Control": "public, max-age=31536000, immutable",
  },
};

const body = Object.entries(rules)
  .map(([path, headers]) =>
    [path, ...Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`)].join(
      "\n",
    ),
  )
  .join("\n\n");

const out = resolve(import.meta.dirname, "../public/_headers");
writeFileSync(
  out,
  `# Generated by scripts/generate-headers.ts. Do not edit.\n${body}\n`,
);
console.log(`_headers: ${Object.keys(rules).length} path rules`);
